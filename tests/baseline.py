# -*- coding: utf-8 -*-
"""Единый источник ожидаемых значений для тестов.

Зачем. Факт «в манифесте 47 строк» был зашит литералом в 11 тестах. Любая
правка манифеста роняла все одиннадцать, и это уже случалось: то же самое
происходило с номером версии алгоритма в test_stage8.py — три падения
подряд на Этапах 8, 10 и при правиле навигации. Класс зафиксирован в пуле
как B-01.

Правило (CONVENTIONS.md раздел 12): ожидаемое значение, которое выводится
из репозитория, хранится здесь в одном экземпляре. Тест читает его отсюда.
Добавление сущности в манифест правит одну строку этого файла, а не
одиннадцать тестов.

Что сюда НЕ кладётся:
  * инварианты — «образов должно быть семь», «подкатегорий не меньше N».
    Их падение и есть сигнал, выносить их отсюда значит ослабить проверку;
  * границы — `> 30`, `>= 1`. Это не копия факта, а требование;
  * факты, которые тест и так вычисляет сам и сравнивает между собой.

Различение копии факта и инварианта — по признаку: если значение меняется
само при штатной правке репозитория, это копия, и ей место здесь. Если оно
меняется только по решению — это инвариант, и он остаётся в тесте.
"""
import csv, io, os

# Корень берётся из ROOT, если он задан: тогда копия репозитория читает
# свой baseline.csv, а не файл оригинала.
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('ROOT') or os.path.dirname(HERE)
BASELINE = os.path.join(ROOT, 'tests', 'baseline.csv')

_cache = None


def _load():
    global _cache
    if _cache is None:
        _cache = {}
        with io.open(BASELINE, encoding='utf-8') as fh:
            for row in csv.DictReader(fh):
                _cache[row['key'].strip()] = int(row['value'])
    return _cache


def expected(key):
    """Ожидаемое значение по ключу. KeyError — ключ не объявлен в baseline.csv."""
    return _load()[key]
